def render(template: str, **kwargs: object) -> str:
    """Подставить kwargs в шаблон через str.format.

    Специально не используем f-строки и не вызываем format на самих
    шаблонах: если в подставляемом содержимом (коде, README) встретятся
    фигурные скобки, .format() на шаблоне их не тронет — они уже внутри
    значения. Единственный риск — фигурные скобки в самом шаблоне, но
    их там нет.
    """
    return template.format(**kwargs)
